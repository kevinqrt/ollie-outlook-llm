import json
import logging

import httpx
from pydantic import ValidationError
from rag_service_api import Client, DirectQueryRequest, HTTPValidationError, direct_query

from app.api.schemas.action_schema import EmailActionResponseSchema
from app.api.schemas.chat_schema import ChatMessageSchema
from app.core.config import settings
from app.services.prompt_service import PromptService
from app.services.vector_store_service import VectorStoreService

logger = logging.getLogger(__name__)


class LlmServiceError(RuntimeError):
    pass


class LlmService:
    def __init__(self, vector_store: VectorStoreService, prompt_service: PromptService) -> None:
        self.prompt_service = prompt_service
        self.vector_store = vector_store
        self.client = Client(
            base_url=settings.rag_service_url,
            timeout=httpx.Timeout(60.0),
            raise_on_unexpected_status=True,
        )

    async def _get_kb_context(
        self,
        query: str,
        k: int = 3,
        header: str = "Relevant Information from Knowledge Base:",
    ) -> str:
        """Helper to fetch and format context from the vector store.

        Best-effort: a vector store failure would otherwise crash the whole
        request with a non-JSON 500 (Starlette's default error page), so it
        is logged and swallowed instead of enriching the prompt.
        """
        if not query:
            return ""
        try:
            results = await self.vector_store.search(query, k=k)
        except Exception:
            logger.exception("Vector store lookup failed, continuing without KB context.")
            return ""
        if not results:
            return ""
        return f"\n\n{header}\n" + "\n".join([r.content for r in results])

    async def generate_suggestion(self, email_text: str) -> str:
        """Call the RAG service to obtain an AI-generated answer suggestion.

        Retrieves additional context from the local vector store if available.

        Raises:
            LlmServiceError: If communication with the RAG service fails or
                an invalid response is returned.
        """
        # Retrieve context from Vector Store
        kb_context = await self._get_kb_context(
            email_text, k=2, header="Additional Knowledge Base Context:"
        )

        query_text = self.prompt_service.get_reply_prompt(email_text)

        request_body = DirectQueryRequest(
            documents_text=(email_text + kb_context) or "No content available.",
            query=query_text,
            llm_model=settings.llm_model,
        )

        try:
            response = await direct_query.asyncio(
                client=self.client,
                body=request_body,
            )

            if response is None:
                raise LlmServiceError("RAG Service returned no response.")

            if isinstance(response, HTTPValidationError):
                raise LlmServiceError(f"RAG Service validation error: {response.detail}")

            reply = response.additional_properties.get(
                "reply"
            ) or response.additional_properties.get("answer")
            return str(reply or "No response generated by the model.")

        except Exception as exc:
            if isinstance(exc, LlmServiceError):
                raise
            logger.error(
                "RAG Service Request failed. URL: %s, Error: %s",
                self.client._base_url,
                exc,
            )
            raise LlmServiceError(f"RAG Service request failed: {exc}") from exc

    async def extract_action(
        self,
        email_text: str,
        links: list[str],
        sender: str | None = None,
        subject: str | None = None,
    ) -> EmailActionResponseSchema:
        """Classify an email and extract a directly actionable summary.

        Asks the RAG service for a strict JSON response and validates it against
        EmailActionResponseSchema. Links are never generated by the model itself;
        it only references indexes into the caller-supplied `links` list.

        Raises:
            LlmServiceError: If communication with the RAG service fails, or the
                response cannot be parsed into the expected schema.
        """
        query_text = self.prompt_service.get_action_extraction_prompt(
            email_text, links, sender, subject
        )

        request_body = DirectQueryRequest(
            documents_text=email_text or "No content available.",
            query=query_text,
            llm_model=settings.llm_model,
        )

        try:
            response = await direct_query.asyncio(
                client=self.client,
                body=request_body,
            )

            if response is None:
                raise LlmServiceError("RAG Service returned no response.")

            if isinstance(response, HTTPValidationError):
                raise LlmServiceError(f"RAG Service validation error: {response.detail}")

            raw = response.additional_properties.get(
                "reply"
            ) or response.additional_properties.get("answer")
            if not raw:
                raise LlmServiceError("RAG Service returned an empty response.")

            return self._parse_action_response(str(raw))

        except Exception as exc:
            if isinstance(exc, LlmServiceError):
                raise
            logger.error("Action extraction failed: %s", exc)
            raise LlmServiceError(f"Action extraction failed: {exc}") from exc

    @staticmethod
    def _parse_action_response(raw: str) -> EmailActionResponseSchema:
        """Extract the JSON object from a raw LLM response and validate it.

        Models sometimes wrap JSON in markdown code fences or add stray text
        around it, so this pulls out the outermost {...} block before parsing.
        """
        text = raw.strip()
        if text.startswith("```"):
            text = text.strip("`")
            if text[:4].lower() == "json":
                text = text[4:]

        start, end = text.find("{"), text.rfind("}")
        if start == -1 or end == -1 or end < start:
            raise LlmServiceError(f"RAG Service response did not contain JSON: {raw!r}")

        try:
            data = json.loads(text[start : end + 1])
        except json.JSONDecodeError as exc:
            raise LlmServiceError(f"RAG Service returned invalid JSON: {exc}") from exc

        try:
            return EmailActionResponseSchema.model_validate(data)
        except ValidationError as exc:
            raise LlmServiceError(
                f"RAG Service JSON did not match the expected schema: {exc}"
            ) from exc

    async def chat(self, messages: list[ChatMessageSchema]) -> str:
        """Process a conversation history and return an AI-generated reply.

        Integrates context from the knowledge base based on the latest user message.
        """
        if not messages:
            return "No messages provided."

        # Get the last user message for RAG context retrieval
        user_query = ""
        for msg in reversed(messages):
            if msg.role == "user":
                user_query = msg.content
                break

        kb_context = await self._get_kb_context(user_query, k=3)

        # Construct the conversation history for the model
        # The RAG service might expect a single 'query' and 'documents_text'
        # We will format the conversation into the query field.
        conversation_history = ""
        for msg in messages:
            role_name = "User" if msg.role == "user" else "Assistant"
            conversation_history += f"{role_name}: {msg.content}\n"

        request_body = DirectQueryRequest(
            documents_text=kb_context or "No additional context available.",
            query=conversation_history + "\nAssistant:",
            llm_model=settings.llm_model,
        )

        logger.info("Sending chat request to RAG service: %s", request_body.to_dict())

        try:
            response = await direct_query.asyncio(
                client=self.client,
                body=request_body,
            )

            if response is None:
                raise LlmServiceError("RAG Service returned no response.")

            if isinstance(response, HTTPValidationError):
                logger.error("RAG Service validation error: %s", response.to_dict())
                raise LlmServiceError(f"RAG Service validation error: {response.detail}")

            reply = response.additional_properties.get(
                "reply"
            ) or response.additional_properties.get("answer")
            return str(reply or "No response generated by the model.")

        except Exception as exc:
            if isinstance(exc, LlmServiceError):
                raise
            logger.error("Chat request failed: %s", exc)
            raise LlmServiceError(f"Chat request failed: {exc}") from exc
